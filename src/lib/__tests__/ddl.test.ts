import { describe, expect, it } from 'vitest'
import type { ColumnInfo, TableInfo } from '../api'
import {
  countChanges,
  ddlScript,
  draftFromTable,
  draftWarnings,
  mysqlDefaultExpr,
  newColumn,
  newTableDraft,
  tableStatements,
  validateDraft,
  type TableDraft
} from '../ddl'
import type { Dialect } from '../engines'

const column = (patch: Partial<ColumnInfo> & { name: string }): ColumnInfo => ({
  dataType: 'int',
  nullable: true,
  default: null,
  isPrimaryKey: false,
  isGenerated: false,
  isIdentity: false,
  comment: null,
  extra: null,
  ...patch
})

const usersTable = (dialect: Dialect): TableInfo => ({
  columns: [
    column({
      name: 'id',
      nullable: false,
      isPrimaryKey: true,
      isGenerated: true,
      isIdentity: true,
      extra: dialect === 'mysql' ? 'auto_increment' : null
    }),
    column({
      name: 'email',
      dataType: dialect === 'postgres' ? 'character varying(100)' : 'varchar(100)',
      nullable: false
    }),
    column({
      name: 'status',
      dataType: 'varchar(10)',
      default: dialect === 'mysql' ? 'new' : dialect === 'tsql' ? "('new')" : "'new'::text"
    }),
    column({ name: 'legacy', dataType: 'text' })
  ],
  primaryKey: ['id'],
  indexes: [
    {
      name: dialect === 'mysql' ? 'PRIMARY' : 'users_pkey',
      columns: ['id'],
      unique: true,
      primary: true,
      method: null,
      definition: null
    },
    {
      name: 'ix_users_email',
      columns: ['email'],
      unique: false,
      primary: false,
      method: null,
      definition: null
    }
  ],
  foreignKeys: []
})

const load = (dialect: Dialect): TableDraft =>
  draftFromTable(
    dialect,
    dialect === 'mysql' ? 'app' : dialect === 'tsql' ? 'dbo' : 'public',
    'users',
    usersTable(dialect)
  )

const col = (draft: TableDraft, name: string) => draft.columns.find((c) => c.name === name)!

describe('create table', () => {
  const draft = (dialect: Dialect): TableDraft => {
    const d = newTableDraft(dialect, dialect === 'mysql' ? 'app' : 'public')
    d.name = 'orders'
    const total = newColumn(dialect, {
      name: 'total',
      dataType: 'decimal(10,2)',
      nullable: false,
      default: '0'
    })
    const customer = newColumn(dialect, { name: 'customer_id', dataType: 'bigint' })
    d.columns.push(total, customer)
    d.indexes.push({
      id: 'ix',
      original: null,
      name: '',
      columns: [customer.id],
      unique: false,
      dropped: false
    })
    d.foreignKeys.push({
      id: 'fk',
      original: null,
      name: '',
      columns: [customer.id],
      refSchema: null,
      refTable: 'customers',
      refColumns: ['id'],
      onDelete: 'CASCADE',
      onUpdate: 'NO ACTION',
      dropped: false
    })
    return d
  }

  it('builds PostgreSQL CREATE TABLE with identity, key, index and foreign key', () => {
    expect(tableStatements('postgres', draft('postgres'))).toEqual([
      `CREATE TABLE public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  total decimal(10,2) NOT NULL DEFAULT 0,
  customer_id bigint,
  PRIMARY KEY (id),
  CONSTRAINT fk_orders_customer_id FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE
)`,
      'CREATE INDEX ix_orders_customer_id ON public.orders (customer_id)'
    ])
  })

  it('inlines MySQL indexes so the table is one statement', () => {
    expect(tableStatements('mysql', draft('mysql'))).toEqual([
      `CREATE TABLE \`app\`.\`orders\` (
  \`id\` bigint NOT NULL AUTO_INCREMENT,
  \`total\` decimal(10,2) NOT NULL DEFAULT 0,
  \`customer_id\` bigint NULL,
  PRIMARY KEY (\`id\`),
  INDEX \`ix_orders_customer_id\` (\`customer_id\`),
  CONSTRAINT \`fk_orders_customer_id\` FOREIGN KEY (\`customer_id\`) REFERENCES \`customers\` (\`id\`) ON DELETE CASCADE
)`
    ])
  })

  it('names the T-SQL primary key and wraps the script in a transaction', () => {
    const d = newTableDraft('tsql', 'dbo')
    d.name = 't'
    const statements = tableStatements('tsql', d)
    expect(statements).toEqual([
      'CREATE TABLE [dbo].[t] (\n  [id] int IDENTITY(1,1) NOT NULL,\n  CONSTRAINT [PK_t] PRIMARY KEY ([id])\n)'
    ])
    expect(ddlScript('tsql', statements)).toBe(
      'SET XACT_ABORT ON;\nBEGIN TRANSACTION;\nGO\n' +
        'CREATE TABLE [dbo].[t] (\n  [id] int IDENTITY(1,1) NOT NULL,\n  CONSTRAINT [PK_t] PRIMARY KEY ([id])\n);\nGO\nCOMMIT TRANSACTION;'
    )
  })

  it('adds PostgreSQL column comments', () => {
    const d = newTableDraft('postgres', 'public')
    d.name = 't'
    d.columns[0].comment = "the user's id"
    expect(tableStatements('postgres', d)[1]).toBe(
      "COMMENT ON COLUMN public.t.id IS 'the user''s id'"
    )
  })
})

describe('alter table', () => {
  it('produces nothing for an untouched table', () => {
    for (const dialect of ['postgres', 'mysql', 'tsql'] as const) {
      const d = load(dialect)
      expect(tableStatements(dialect, d)).toEqual([])
      expect(countChanges(d)).toBe(0)
    }
  })

  it('renames, retypes, drops and adds PostgreSQL columns in dependency order', () => {
    const d = load('postgres')
    Object.assign(col(d, 'email'), { name: 'mail', dataType: 'text' })
    col(d, 'status').default = ''
    col(d, 'legacy').dropped = true
    d.columns.push(newColumn('postgres', { name: 'age', dataType: 'int', comment: 'years' }))
    d.indexes[0].dropped = true
    d.name = 'people'
    expect(tableStatements('postgres', d)).toEqual([
      'DROP INDEX public.ix_users_email',
      'ALTER TABLE public.users DROP COLUMN legacy',
      'ALTER TABLE public.users RENAME COLUMN email TO mail',
      'ALTER TABLE public.users ALTER COLUMN mail TYPE text USING mail::text',
      'ALTER TABLE public.users ALTER COLUMN status DROP DEFAULT',
      'ALTER TABLE public.users ADD COLUMN age int',
      "COMMENT ON COLUMN public.users.age IS 'years'",
      'ALTER TABLE public.users RENAME TO people'
    ])
    expect(countChanges(d)).toBe(6)
    expect(draftWarnings(d)).toEqual([
      'Drops column legacy and its data',
      'Changes the type of mail; existing values must convert'
    ])
  })

  it('moves the primary key', () => {
    const d = load('postgres')
    d.primaryKey = [col(d, 'email').id]
    expect(tableStatements('postgres', d)).toEqual([
      'ALTER TABLE public.users DROP CONSTRAINT users_pkey',
      'ALTER TABLE public.users ADD PRIMARY KEY (email)'
    ])
  })

  it('makes a new key column NOT NULL first', () => {
    const d = load('tsql')
    d.primaryKey = [col(d, 'id').id, col(d, 'legacy').id]
    col(d, 'legacy').dataType = 'nvarchar(50)'
    expect(tableStatements('tsql', d)).toEqual([
      'ALTER TABLE [dbo].[users] DROP CONSTRAINT [users_pkey]',
      'ALTER TABLE [dbo].[users] ALTER COLUMN [legacy] nvarchar(50) NOT NULL',
      'ALTER TABLE [dbo].[users] ADD CONSTRAINT [PK_users] PRIMARY KEY ([id], [legacy])'
    ])
  })

  it('merges MySQL changes into one ALTER TABLE and restates the full column', () => {
    const d = load('mysql')
    expect(col(d, 'status').default).toBe("'new'")
    Object.assign(col(d, 'status'), { name: 'state', nullable: false })
    col(d, 'legacy').dropped = true
    d.columns.push(newColumn('mysql', { name: 'note', comment: 'free text' }))
    expect(tableStatements('mysql', d)).toEqual([
      'ALTER TABLE `app`.`users`\n' +
        '  DROP COLUMN `legacy`,\n' +
        "  CHANGE COLUMN `status` `state` varchar(10) NOT NULL DEFAULT 'new',\n" +
        "  ADD COLUMN `note` varchar(255) NULL COMMENT 'free text'"
    ])
  })

  it('keeps MySQL AUTO_INCREMENT and ON UPDATE when modifying a column', () => {
    const info: TableInfo = {
      columns: [
        column({
          name: 'id',
          nullable: false,
          isGenerated: true,
          isIdentity: true,
          extra: 'auto_increment'
        }),
        column({
          name: 'updated',
          dataType: 'timestamp',
          default: 'CURRENT_TIMESTAMP',
          isGenerated: true,
          extra: 'DEFAULT_GENERATED on update CURRENT_TIMESTAMP'
        })
      ],
      primaryKey: ['id'],
      indexes: [],
      foreignKeys: []
    }
    const d = draftFromTable('mysql', 'app', 't', info)
    expect(col(d, 'updated').computed).toBe(false)
    col(d, 'id').dataType = 'bigint'
    col(d, 'updated').nullable = false
    expect(tableStatements('mysql', d)).toEqual([
      'ALTER TABLE `app`.`t`\n' +
        '  MODIFY COLUMN `id` bigint NOT NULL AUTO_INCREMENT,\n' +
        '  MODIFY COLUMN `updated` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP'
    ])
  })

  it('drops and restores SQL Server default constraints around column changes', () => {
    const d = load('tsql')
    Object.assign(col(d, 'status'), { name: 'state', dataType: 'varchar(20)' })
    const statements = tableStatements('tsql', d)
    expect(statements).toHaveLength(4)
    expect(statements[0]).toContain(
      "WHERE d.parent_object_id = OBJECT_ID(N'[dbo].[users]') AND c.name = N'status'"
    )
    expect(statements.slice(1)).toEqual([
      "EXEC sp_rename N'[dbo].[users].[status]', N'state', 'COLUMN'",
      'ALTER TABLE [dbo].[users] ALTER COLUMN [state] varchar(20) NULL',
      "ALTER TABLE [dbo].[users] ADD CONSTRAINT [DF_users_state] DEFAULT ('new') FOR [state]"
    ])
  })

  it('drops a SQL Server default before dropping its column', () => {
    const d = load('tsql')
    col(d, 'status').dropped = true
    const statements = tableStatements('tsql', d)
    expect(statements[0]).toMatch(/^DECLARE @sql/)
    expect(statements[1]).toBe('ALTER TABLE [dbo].[users] DROP COLUMN [status]')
  })

  it('changes Babelfish defaults in place instead of dropping constraints', () => {
    const d = load('tsql')
    Object.assign(col(d, 'status'), { dataType: 'varchar(20)', nullable: false, default: '' })
    col(d, 'legacy').dropped = true
    expect(tableStatements('tsql', d, { babelfish: true })).toEqual([
      'ALTER TABLE [dbo].[users] DROP COLUMN [legacy]',
      'ALTER TABLE [dbo].[users] ALTER COLUMN [status] varchar(20) NOT NULL',
      'ALTER TABLE [dbo].[users] ADD CONSTRAINT [DF_users_status] DEFAULT NULL FOR [status]'
    ])
  })

  it('toggles PostgreSQL identity', () => {
    const d = load('postgres')
    col(d, 'id').identity = false
    expect(tableStatements('postgres', d)).toEqual([
      'ALTER TABLE public.users ALTER COLUMN id DROP IDENTITY'
    ])
  })

  it('leaves computed columns alone', () => {
    const info: TableInfo = {
      columns: [column({ name: 'total', isGenerated: true, default: '(price * qty)' })],
      primaryKey: [],
      indexes: [],
      foreignKeys: []
    }
    const d = draftFromTable('tsql', 'dbo', 't', info)
    expect(d.columns[0].computed).toBe(true)
    d.columns[0].dataType = 'bigint'
    expect(tableStatements('tsql', d)).toEqual([])
  })
})

describe('validateDraft', () => {
  it('reports missing names and duplicates', () => {
    const d = newTableDraft('postgres', 'public')
    expect(validateDraft('postgres', d)).toBe('Enter a table name')
    d.name = 't'
    d.columns.push(newColumn('postgres', { name: 'ID' }))
    expect(validateDraft('postgres', d)).toBe('There are two columns named ID')
    d.columns[1].name = ''
    expect(validateDraft('postgres', d)).toBe('Every column needs a name')
  })

  it('requires matching foreign key columns', () => {
    const d = newTableDraft('mysql', 'app')
    d.name = 't'
    d.foreignKeys.push({
      id: 'fk',
      original: null,
      name: 'fk_t',
      columns: [d.columns[0].id],
      refSchema: null,
      refTable: 'other',
      refColumns: [],
      onDelete: 'NO ACTION',
      onUpdate: 'NO ACTION',
      dropped: false
    })
    expect(validateDraft('mysql', d)).toBe(
      'Foreign key fk_t needs as many referenced columns as columns'
    )
  })
})

describe('mysqlDefaultExpr', () => {
  it('quotes MySQL 8 literals and keeps expressions', () => {
    expect(mysqlDefaultExpr(null, 'int')).toBe('')
    expect(mysqlDefaultExpr('0', 'int')).toBe('0')
    expect(mysqlDefaultExpr('abc', 'varchar(10)')).toBe("'abc'")
    expect(mysqlDefaultExpr("'abc'", 'varchar(10)')).toBe("'abc'")
    expect(mysqlDefaultExpr('CURRENT_TIMESTAMP', 'timestamp')).toBe('CURRENT_TIMESTAMP')
    expect(mysqlDefaultExpr('uuid()', 'char(36)')).toBe('(uuid())')
    expect(mysqlDefaultExpr("lower(_latin1\\'A\\')", 'char(36)')).toBe("(lower(_latin1'A'))")
    expect(mysqlDefaultExpr('', 'varchar(10)')).toBe("''")
  })
})
